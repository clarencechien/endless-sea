import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const artifacts=process.env.ARTIFACTS_DIR||'/tmp/endless-sea-artifacts';
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('canvas').dataset.ready==='true');
 assert.ok(await page.evaluate(()=>window.endlessSea.getRenderer().triangles)>5000);
 await page.screenshot({path:`${artifacts}/desktop.png`});
 await page.locator('#fly').click();
 assert.equal(await page.evaluate(()=>window.endlessSea.getState().flying),true);
 await page.keyboard.down('d');
 await page.waitForFunction(()=>!window.endlessSea.getState().autopilot&&window.endlessSea.getState().heading<-.005);
 await page.keyboard.up('d');
 assert.equal(await page.locator('#autopilot').getAttribute('aria-pressed'),'false');
 await page.keyboard.press('p');
 assert.equal(await page.locator('#autopilot').getAttribute('aria-pressed'),'true');
 await page.locator('[data-time="blue"]').click();
 assert.ok(await page.evaluate(()=>Math.abs(window.endlessSea.getState().journey.hours-19.5)<.1));
 await page.locator('#settings').click();
 await page.locator('#quality').selectOption('1');
 await page.locator('#wind').fill('1.2');
 assert.equal(await page.evaluate(()=>window.endlessSea.getState().wind),1.2);
 await page.locator('.close-panel').click();
 await page.locator('#sound').click();
 assert.equal(await page.locator('#sound').getAttribute('aria-label'),'關閉環境音');
 await page.waitForFunction(()=>window.endlessSea.getState().audio?.notesPlayed>0&&window.endlessSea.getState().audio?.rms>.00001);
 await page.locator('#settings').click();
 for(const name of ['music','engine','wind','sea'])await page.locator(`[data-mix="${name}"]`).fill('0');
 await page.waitForFunction(()=>window.endlessSea.getState().audio.rms<.00001);
 for(const name of ['music','engine','wind','sea']){
  await page.locator(`[data-mix="${name}"]`).fill('0.8');
  await page.waitForFunction(()=>window.endlessSea.getState().audio.rms>.00001);
  await page.locator(`[data-mix="${name}"]`).fill('0');
  await page.waitForFunction(()=>window.endlessSea.getState().audio.rms<.00001);
 }
 await page.locator('[data-mix="music"]').fill('0.65');
 const downloadPromise=page.waitForEvent('download');await page.locator('#download-midi').click();const download=await downloadPromise;assert.equal(download.suggestedFilename(),'endless-sea-chapter-1.mid');
 await page.locator('.close-panel').click();
 await page.locator('#sound').click();
 await page.locator('#help').click();assert.equal(await page.locator('#guide').evaluate(el=>el.open),true);
 await page.keyboard.press('Escape');assert.equal(await page.locator('#guide').evaluate(el=>el.open),false);
 await page.keyboard.press('h');assert.ok(await page.locator('body').evaluate(el=>el.classList.contains('ui-hidden')));
 await page.locator('#restore-ui').click();
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('ui-hidden')),false);
 await page.keyboard.press('r');
 assert.equal(await page.evaluate(()=>window.endlessSea.getState().autopilot),true);
 await page.screenshot({path:`${artifacts}/blue-flight.png`});
 await page.locator('#chapter-select').selectOption('2');
 await page.waitForFunction(()=>window.endlessSea.getState().chapter===2&&window.endlessSea.getRenderer().triangles>200000);
 assert.equal(await page.evaluate(()=>window.endlessSea.getState().audio.chapter),2);
 await page.screenshot({path:`${artifacts}/islands.png`});
 await page.locator('#fullscreen').click();
 await page.waitForFunction(()=>!!document.fullscreenElement&&document.querySelector('#fullscreen').getAttribute('aria-pressed')==='true');
 assert.equal(await page.locator('#fullscreen').getAttribute('aria-pressed'),'true');
 await page.locator('#fullscreen').click();
 await page.waitForFunction(()=>!document.fullscreenElement);
 await page.locator('#chapter-select').selectOption('1');
 await page.waitForFunction(()=>window.endlessSea.getRenderer().triangles<10000);
 await page.locator('[data-time="night"]').click();
 await page.waitForFunction(()=>window.endlessSea.getState().journey.hours<1);
 await page.screenshot({path:`${artifacts}/night.png`});
 assert.ok(await page.evaluate(()=>window.endlessSea.getState().journey.beats)>0);
 await page.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.addInitScript(()=>{DeviceOrientationEvent.requestPermission=async()=>'granted';});
 await mobile.goto(process.env.APP_URL||'http://127.0.0.1:5173',{waitUntil:'networkidle'});
 await mobile.waitForFunction(()=>document.querySelector('canvas').dataset.ready==='true');
 await mobile.screenshot({path:`${artifacts}/mobile.png`});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth),390);
 await mobile.locator('#fly').tap();
 assert.ok(await mobile.locator('#touch-controls').isVisible());
 const button=await mobile.locator('[data-key="s"]').boundingBox();
 const cdp=await mobile.context().newCDPSession(mobile);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:button.x+button.width/2,y:button.y+button.height/2}]});
 await mobile.waitForFunction(()=>window.endlessSea.getState().pitch>.01);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.equal(await mobile.evaluate(()=>window.endlessSea.getState().autopilot),false);
 await mobile.locator('#chapter-select').selectOption('2');
 await mobile.waitForFunction(()=>window.endlessSea.getState().chapter===2);
 await mobile.screenshot({path:`${artifacts}/islands-mobile.png`});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth),390);
 await mobile.locator('#settings').tap();
 await mobile.locator('#tilt-toggle').tap();
 await mobile.evaluate(()=>{window.dispatchEvent(new DeviceOrientationEvent('deviceorientation',{beta:45,gamma:0}));for(let i=0;i<20;i++)window.dispatchEvent(new DeviceOrientationEvent('deviceorientation',{beta:65,gamma:20}));});
 await mobile.waitForFunction(()=>window.endlessSea.getState().tilt.roll>.5&&window.endlessSea.getState().pitch>.03);
 assert.equal(await mobile.evaluate(()=>window.endlessSea.getState().autopilot),false);
 await mobile.locator('#tilt-calibrate').tap();
 assert.equal(await mobile.evaluate(()=>window.endlessSea.getState().tilt.roll),0);
 await mobile.locator('#tilt-toggle').tap();
 assert.equal(await mobile.evaluate(()=>window.endlessSea.getState().tilt.enabled),false);
 await mobile.evaluate(()=>{DeviceOrientationEvent.requestPermission=async()=>'denied';});
 await mobile.locator('#tilt-toggle').tap();
 assert.equal(await mobile.evaluate(()=>window.endlessSea.getState().tilt.enabled),false);
 assert.ok((await mobile.locator('#tilt-status').textContent()).includes('未取得'));
 assert.deepEqual(errors,[]);
 console.log('PASS: rendered 3D scene; manual flight; autopilot; atmosphere; quality; wind; audio; guide; hide/reset; mobile layout and touch flight; island chapter; four independently audible mixer buses; MIDI download; fullscreen enter/exit; simulated tilt permissions, steering and calibration; night sky and beat counter.');
 console.log(`Screenshots: ${artifacts}`);
} finally {await browser.close();}
